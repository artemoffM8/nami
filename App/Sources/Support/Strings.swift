//  Централизованный словарь строк. Доменные слои возвращают только КЛЮЧИ
//  (`ResultReasonCode.localizationKey`, `SudokuTechnique.nameKey` и т.д.),
//  а конкретный текст живёт здесь — так формула рейтинга и solver не знают
//  ничего о copy и локализации.
//
//  Два языка лежат в обычных словарях, а не в .lproj, сознательно:
//  ключи приходят из чистого Swift-пакета, который не имеет права знать
//  про Bundle, а тест `LocalizationTests` проверяет, что наборы ключей
//  и форматные спецификаторы в `ru` и `en` совпадают. При переходе на
//  String Catalog меняется только реализация `t`.
//

import Foundation
import NamiData

enum L {

    enum Language: String, Sendable, CaseIterable {
        case ru, en
    }

    /// Язык интерфейса. Статический, потому что строки нужны из мест, где нет
    /// доступа к @Environment (инициализаторы, форматтеры, accessibility-метки).
    /// Пишется ровно дважды: при старте и из экрана настроек, всегда с MainActor.
    nonisolated(unsafe) static var language: Language = systemLanguage()

    /// Первый язык устройства, который мы умеем показывать.
    /// Для всего остального английский полезнее русского.
    static func systemLanguage() -> Language {
        for code in Locale.preferredLanguages {
            let base = code.split(separator: "-").first.map(String.init) ?? code
            if let match = Language(rawValue: base.lowercased()) { return match }
        }
        return .en
    }

    /// Применяет настройку игрока. `.system` возвращает язык устройству.
    static func apply(_ preference: PreferencesRepository.AppLanguage) {
        switch preference {
        case .system: language = systemLanguage()
        case .ru: language = .ru
        case .en: language = .en
        }
    }

    private static var table: [String: String] { language == .ru ? ru : en }

    static func t(_ key: String) -> String {
        // Русский — язык оригинала, поэтому он же и последний рубеж:
        // пропущенный перевод покажет текст, а не сырой ключ.
        table[key] ?? ru[key] ?? key
    }

    static func t(_ key: String, _ arguments: CVarArg...) -> String {
        let format = table[key] ?? ru[key] ?? key
        // Несовпадение спецификатора и типа аргумента роняет String(format:)
        // насмерть. Текст в интерфейсе не стоит падения приложения: проверяем
        // соответствие заранее и в крайнем случае отдаём сырой формат.
        guard formatMatches(format, arguments) else {
            // Ронять приложение из-за строки нельзя: несовпадение ловит
            // статическая проверка в Tools/verify_project.py ещё до сборки.
            #if DEBUG
            print("[strings] аргументы не совпадают с форматом ключа \(key)")
            #endif
            return format
        }
        return String(format: format, arguments: arguments)
    }

    /// Грубая, но достаточная проверка: число и род спецификаторов против
    /// фактических типов. `%@` требует строку, `%d`/`%f` — число.
    private static func formatMatches(_ format: String, _ arguments: [CVarArg]) -> Bool {
        var expected: [Character] = []
        var iterator = format.makeIterator()
        while let character = iterator.next() {
            guard character == "%" else { continue }
            var kind: Character?
            while let next = iterator.next() {
                if next == "%" { break }                    // экранированный процент
                if "@dfsu".contains(next) { kind = next; break }
            }
            if let kind { expected.append(kind) }
        }
        guard expected.count == arguments.count else { return false }
        for (kind, argument) in zip(expected, arguments) {
            let isString = argument is String || argument is NSString
            if kind == "@" && !isString { return false }
            if kind != "@" && isString { return false }
        }
        return true
    }

